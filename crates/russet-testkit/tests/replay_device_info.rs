//! QA-06: record a device session through [`RecordingConnector`] and replay it through [`ReplayConnector`],
//! with no device and no sockets, so it runs on Linux and Windows CI (PLAN W15 acceptance).
//!
//! The headline test records the facade calls `russet device info` makes against the scripted iPhone, writes an
//! RDT trace, replays it, and asserts the same [`DeviceInfo`]. A second test replays the committed fixture and
//! checks that it is redaction-clean (DC-13 "trace lint clean").

use std::sync::Arc;
use std::time::Duration;

use russet_device::io::ServiceConnector;
use russet_device::{DeviceConfig, DeviceInfo, DeviceManager, DeviceSelector};
use russet_testkit::rdt::{Device, Header, Redaction, Trace, VERSION};
use russet_testkit::redaction;
use russet_testkit::{RecordingConnector, ReplayConnector, ReplayMode, Scenario, ScriptedConnector};

const UDID: &str = "00000000-0000000000000001";

/// The committed fixture `cargo xtask traces lint` and the fixture test use.
fn fixture_path() -> std::path::PathBuf {
    russet_testkit::testkit_dir().join("traces/device-info/27.0-24A437/iPhone13-2.rdt.jsonl")
}

fn device_info_header() -> Header {
    Header {
        rdt: VERSION,
        scenario: "device-info".into(),
        recorded_at: "2026-10-11T00:00:00Z".into(),
        russet: "0.1.0".into(),
        idevice: "0.1.68".into(),
        host_os: "linux".into(),
        device: Device {
            product_type: "iPhone13,2".into(),
            product_version: "27.0".into(),
            build_version: "24A437".into(),
            csm: "txm".into(),
            udid: UDID.into(),
            transport: "usb".into(),
        },
        redaction: Redaction::default(),
    }
}

fn config(tmp: &std::path::Path) -> DeviceConfig {
    DeviceConfig { state_dir: tmp.join("state"), runtime_dir: tmp.join("runtime"), ..Default::default() }
}

/// Starts a manager on `conn`, waits for the device to appear, and reads `device info`.
async fn device_info(conn: Arc<dyn ServiceConnector>, tmp: &std::path::Path) -> DeviceInfo {
    let m = DeviceManager::start(config(tmp), conn).await.expect("device manager starts");
    for _ in 0..500 {
        if let Ok(h) = m.get(&DeviceSelector::Only) {
            return h.info().await.expect("device info");
        }
        tokio::time::sleep(Duration::from_millis(10)).await;
    }
    panic!("the device never appeared");
}

fn same(a: &DeviceInfo, b: &DeviceInfo) {
    assert_eq!(a.udid, b.udid, "udid");
    assert_eq!(a.identity.product_type, b.identity.product_type, "product type");
    assert_eq!(a.identity.os_version, b.identity.os_version, "os version");
    assert_eq!(a.identity.build, b.identity.build, "build");
    assert_eq!(a.identity.name, b.identity.name, "name");
    assert_eq!(a.properties, b.properties, "properties");
}

#[tokio::test]
async fn record_then_replay_device_info() {
    let tmp = tempfile::tempdir().expect("tempdir");

    // Record `device info` against the scripted iPhone.
    let scripted = ScriptedConnector::new(Scenario::default_scenario());
    let recorder = Arc::new(RecordingConnector::new(scripted, device_info_header()));
    let recorded = device_info(recorder.clone() as Arc<dyn ServiceConnector>, &tmp.path().join("record")).await;
    assert_eq!(recorded.identity.product_type.as_deref(), Some("iPhone13,2"));
    assert_eq!(recorded.identity.os_version.as_deref(), Some("27.0"));

    // The trace round-trips through disk (plain JSON Lines here; `.zst` is supported too).
    let trace_path = tmp.path().join("device-info.rdt.jsonl");
    recorder.write(&trace_path).expect("write trace");
    let trace = Trace::read(&trace_path).expect("read trace");
    assert!(trace.records.iter().any(|r| matches!(r, russet_testkit::rdt::Record::Call { .. })), "calls were recorded");
    assert!(redaction::lint(&trace).is_empty(), "the recorded trace is redaction-clean: {:?}", redaction::lint(&trace));

    // Replay the trace: the same `device info`, with no device.
    let replay = ReplayConnector::open(&trace_path, ReplayMode::Semantic).expect("open replay");
    let replayed = device_info(Arc::new(replay) as Arc<dyn ServiceConnector>, &tmp.path().join("replay")).await;
    same(&recorded, &replayed);

    // Bless the committed fixture when asked (RUSSET_WRITE_FIXTURE=1).
    if std::env::var_os("RUSSET_WRITE_FIXTURE").is_some() {
        recorder.write(&fixture_path()).expect("write fixture");
    }
}

#[tokio::test]
async fn the_committed_fixture_replays_and_is_clean() {
    let path = fixture_path();
    if !path.exists() {
        // The fixture is generated by `record_then_replay_device_info` under RUSSET_WRITE_FIXTURE=1.
        eprintln!("skipping: {} is not present", path.display());
        return;
    }
    let trace = Trace::read(&path).expect("read fixture");
    let findings = redaction::lint(&trace);
    assert!(findings.is_empty(), "the committed trace must be redaction-clean: {findings:?}");

    let tmp = tempfile::tempdir().expect("tempdir");
    let replay = ReplayConnector::open(&path, ReplayMode::Semantic).expect("open replay");
    let info = device_info(Arc::new(replay) as Arc<dyn ServiceConnector>, tmp.path()).await;
    assert_eq!(info.udid.0, UDID);
    assert_eq!(info.identity.product_type.as_deref(), Some("iPhone13,2"));
    assert_eq!(info.identity.os_version.as_deref(), Some("27.0"));
}
